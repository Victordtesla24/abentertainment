const IMAGES_ROOT = '/images/';

/** Largest generated width that is still a sensible default for browsers that ignore srcset. */
const DEFAULT_SRC_MAX_WIDTH = 1024;

interface OptimizedImageProps {
  src: string;
  alt: string;
  /** Intrinsic size of the artwork — reserves the aspect ratio before the file arrives. */
  width: number;
  height: number;
  /** Rendered width hint for srcset selection, e.g. "(max-width: 768px) 100vw, 50vw". */
  sizes?: string;
  /** Above-the-fold / LCP image: eager, high fetch priority and a preload hint. */
  priority?: boolean;
  /** Set false for a small `priority` image (e.g. the header logo) that does not need its own preload link. */
  preload?: boolean;
  /** Overrides the fetch priority implied by `priority` (e.g. "low" for artwork warmed ahead of use). */
  fetchPriority?: 'high' | 'low' | 'auto';
  className?: string;
  style?: CSSProperties;
  blurPlaceholder?: boolean;
  /** Called when the image cannot be shown at all (after the original-file retry). */
  onError?: () => void;
}

/**
 * The largest generated variant of a source image (JPEG/PNG fallback format), for
 * viewers that want full resolution without fetching the multi-megabyte original.
 * Sources outside the variant plan are returned unchanged.
 */
export function largestVariantSrc(src: string): string {
  const relPath = src.startsWith(IMAGES_ROOT) ? src.slice(IMAGES_ROOT.length) : null;
  const plan = relPath ? profileFor(relPath) : null;
  if (!relPath || !plan) return src;
  return `${IMAGES_ROOT}${variantPath(relPath, plan.widths[plan.widths.length - 1], plan.fallback)}`;
}

/**
 * Responsive image with AVIF -> WebP -> JPEG/PNG negotiation.
 *
 * Images in the folders described by scripts/image-profiles.mjs are rendered as
 * a <picture> whose srcsets point at the variants generated by
 * scripts/optimize-images.mjs (widths from 64 px up to the source resolution),
 * so a phone never downloads a desktop-sized file and the original multi-megabyte
 * artwork is never a candidate. Everything else (admin uploads, remote URLs,
 * other folders) is rendered as a single <img> of the file as given.
 */
export default function OptimizedImage({
  src,
  alt,
  width,
  height,
  sizes = '100vw',
  priority = false,
  preload: emitPreload = priority,
  fetchPriority,
  className,
  style,
  blurPlaceholder = false,
  onError,
}: OptimizedImageProps) {
  const imgRef = useRef<HTMLImageElement>(null);
  const usable = isUsableImageUrl(src);
  const reportedRef = useRef(false);
  const relPath = src.startsWith(IMAGES_ROOT) ? src.slice(IMAGES_ROOT.length) : null;
  const plan = relPath ? profileFor(relPath) : null;

  /**
   * A <source> that 404s does not fall back to the next <source>. If a variant is
   * missing (an image added after the last build), drop the sources and reload the
   * original so the picture is never left broken.
   */
  const restoreOriginal = (img: HTMLImageElement) => {
    if (img.dataset.restored) return;
    img.dataset.restored = 'true';
    img.parentElement?.querySelectorAll('source').forEach((source) => source.remove());
    img.removeAttribute('srcset');
    img.removeAttribute('sizes');
    img.src = src;
  };
  const handleError = (event: SyntheticEvent<HTMLImageElement>) => {
    const img = event.currentTarget;
    if (plan && !img.dataset.restored) restoreOriginal(img);
    else onError?.();
  };

  // A page link (e.g. Google Photos) is not an image: render nothing and let the caller
  // fall back, exactly as if the file had failed to load, without issuing the request.
  useEffect(() => {
    if (usable) {
      reportedRef.current = false;
    } else if (!reportedRef.current) {
      reportedRef.current = true;
      onError?.();
    }
  }, [usable, onError]);

  // An error that fired before hydration never reaches React's onError.
  useEffect(() => {
    const img = imgRef.current;
    if (plan && img && img.complete && img.naturalWidth === 0 && img.currentSrc) restoreOriginal(img);
  }, [plan, src]);

  const imgStyle: CSSProperties | undefined =
    blurPlaceholder && !priority
      ? {
          backgroundImage: `url(${BLUR_SVG_DATA_URL})`,
          backgroundSize: 'cover',
          backgroundRepeat: 'no-repeat',
          ...style,
        }
      : style;

  const imgProps = {
    alt,
    width,
    height,
    loading: priority ? ('eager' as const) : ('lazy' as const),
    fetchPriority: fetchPriority ?? (priority ? ('high' as const) : ('auto' as const)),
    decoding: 'async' as const,
    className,
    style: imgStyle,
    onError: handleError,
  };

  if (!usable) return null;

  if (!relPath || !plan) {
    if (emitPreload) preload(src, { as: 'image', fetchPriority: 'high' });
    return <img ref={imgRef} src={src} {...imgProps} />;
  }

  const srcSetFor = (format: string) =>
    plan.widths.map((w) => `${IMAGES_ROOT}${variantPath(relPath, w, format)} ${w}w`).join(', ');
  const defaultWidth =
    [...plan.widths].reverse().find((w) => w <= DEFAULT_SRC_MAX_WIDTH) ?? plan.widths[plan.widths.length - 1];

  if (emitPreload) {
    // <picture> children are not discovered by React's automatic image preloading,
    // so hint the AVIF candidates explicitly. Browsers without AVIF skip this link
    // (type mismatch) and discover the right file from the markup as usual.
    preload(`${IMAGES_ROOT}${variantPath(relPath, defaultWidth, 'avif')}`, {
      as: 'image',
      type: 'image/avif',
      imageSrcSet: srcSetFor('avif'),
      imageSizes: sizes,
      fetchPriority: 'high',
    });
  }

  return (
    <picture>
      {MODERN_FORMATS.map((format) => (
        <source key={format} type={`image/${format}`} srcSet={srcSetFor(format)} sizes={sizes} />
      ))}
      <img
        ref={imgRef}
        src={`${IMAGES_ROOT}${variantPath(relPath, defaultWidth, plan.fallback)}`}
        srcSet={srcSetFor(plan.fallback)}
        sizes={sizes}
        {...imgProps}
      />
    </picture>
  );
}
